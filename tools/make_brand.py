"""Writes everything that comes from brand/brand.json:

  brand.css          the colors, stage colors and fonts as CSS variables, plus
                     the small icons drawn inside the CSS (they can't use variables)
  site.webmanifest   theme and background colors
  *.html             each page's theme-color, web-font link and header logo

Run it after any change to brand/brand.json:

    python3 tools/make_brand.py           # write the files
    python3 tools/make_brand.py --check   # just say whether they're up to date

The tests run --check, so a brand.json edit that wasn't followed by this
command fails the test run instead of quietly shipping old colors.
"""
import json, os, re, sys
from urllib.parse import quote

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)
import branding  # noqa: E402

PAGES = ["index.html", "about.html", "stats.html", "glossary.html", "404.html", "styleguide.html", "admin/index.html"]


def svg_url(svg):
    """An SVG as a CSS url(), escaped the same way the stylesheet always has."""
    return 'url("data:image/svg+xml,' + svg.replace("<", "%3C").replace(">", "%3E").replace("#", "%23").replace('"', "'") + '")'


def icons(c):
    return {
        # The dropdown arrow on selects and pickers.
        "icon-chevron": svg_url(f"<svg xmlns='http://www.w3.org/2000/svg' width='10' height='6'><path d='M1 1l4 4 4-4' fill='none' stroke='{c['ink']}' stroke-width='1.5'/></svg>"),
        # The tick and dash inside ticked and half-ticked checkboxes.
        "icon-check": svg_url(f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 11 11'><path d='M2 5.6 4.4 8 9 3' fill='none' stroke='{c['paper']}' stroke-width='1.7'/></svg>"),
        "icon-dash": svg_url(f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 11 11'><path d='M2.5 5.5h6' stroke='{c['paper']}' stroke-width='1.7'/></svg>"),
    }


def css():
    b, c = branding.BRAND, branding.COLORS
    out = ["/* Generated by tools/make_brand.py from brand/brand.json. Don't edit this file:",
           "   change brand.json and run  python3 tools/make_brand.py  */", "", ":root {"]
    width = max(len(k) for k in c) + 3
    for name, col in b["colors"].items():
        out.append(f"  --{name}:".ljust(width + 4) + f"{col['value']};   /* {col['use']} */")
    out.append("")
    out.append("  /* Stages, in order. The map and charts get these from projects.json; CSS uses them for keys and samples. */")
    for i, s in enumerate(b["stages"]):
        out.append(f"  --stage-{i}: {s['color']};   /* {s['name']} */")
    out.append("")
    out.append(f"  --logo-src: \"/{b['logo']['main']}\";   /* for images drawn in the browser (map export, chart downloads) */")
    f = b["fonts"]
    out.append("  /* Type. Headlines use --display at --display-weight and --display-stretch. */")
    out.append(f"  --display: {f['display']['family']};")
    out.append(f"  --display-weight: {f['display']['weight']};")
    out.append(f"  --display-stretch: {f['display'].get('stretch', '100%')};")
    out.append(f"  --display-em-style: {f['display'].get('emStyle', 'italic')};   /* the 'in Progress' in the site name */")
    out.append(f"  --display-em-weight: {f['display'].get('emWeight', f['display']['weight'])};")
    out.append(f"  --deck: {f['deck']['family']};")
    out.append(f"  --deck-weight: {f['deck']['weight']};")
    out.append(f"  --sans: {f['sans']['family']};")
    out.append("")
    out.append("  /* Type scale (issue #42): every font size and letter-spacing in styles.css. */")
    for name, s in f["scale"].items():
        if not name.startswith("_"):
            out.append(f"  --fs-{name}: {s['size']};   /* {s['use']} */")
    for name, s in f["tracking"].items():
        out.append(f"  --ls-{name}: {s['value']};   /* {s['use']} */")
    out.append("")
    for name, url in icons(c).items():
        out.append(f"  --{name}: {url};")
    out.append("}")
    return "\n".join(out) + "\n"


def manifest(text):
    m = json.loads(text)
    m["theme_color"] = branding.COLORS[branding.BRAND["browser"]["themeColor"]]
    m["background_color"] = branding.COLORS[branding.BRAND["browser"]["backgroundColor"]]
    return json.dumps(m, indent=2, ensure_ascii=False) + "\n"


THEME = re.compile(r'(<meta name="theme-color" content=")#[0-9a-fA-F]{3,6}(">)')
WEBFONTS = re.compile(r'(<link href=")https://fonts\.googleapis\.com/css2\?[^"]*(" rel="stylesheet">)')
LOGO_LINK = re.compile(r'(<a class="lockup__logo" href=")[^"]*(")')
LOGO_IMG = re.compile(r'(<img class="lockup__img" src=")(/?)[^"]*(" alt=")[^"]*(")')


def page(text):
    b = branding.BRAND
    text = THEME.sub(lambda m: m.group(1) + branding.COLORS[b["browser"]["themeColor"]] + m.group(2), text)
    text = WEBFONTS.sub(lambda m: m.group(1) + b["fonts"]["webfonts"] + m.group(2), text)
    # The header logo: its link, file and name come from brand.json.
    text = LOGO_LINK.sub(lambda m: m.group(1) + b["parent"]["url"] + m.group(2), text)
    text = LOGO_IMG.sub(lambda m: m.group(1) + m.group(2) + b["logo"]["main"] + m.group(3) + b["parent"]["name"] + m.group(4), text)
    return text


def outputs():
    """{path: (current text or None, wanted text)}"""
    res = {}
    def cur(rel):
        p = os.path.join(REPO, rel)
        return open(p, encoding="utf-8").read() if os.path.exists(p) else None
    res["brand.css"] = (cur("brand.css"), css())
    m = cur("site.webmanifest")
    res["site.webmanifest"] = (m, manifest(m))
    for rel in PAGES:
        t = cur(rel)
        if t is not None:
            res[rel] = (t, page(t))
    return res


def main(argv):
    stale = [rel for rel, (now, want) in outputs().items() if now != want]
    if "--check" in argv:
        if stale:
            print("Out of date with brand/brand.json:", ", ".join(stale), "\nRun: python3 tools/make_brand.py")
            return 1
        print("Brand files are up to date.")
        return 0
    for rel, (now, want) in outputs().items():
        if now != want:
            with open(os.path.join(REPO, rel), "w", encoding="utf-8") as f:
                f.write(want)
    print("Updated:", ", ".join(stale) if stale else "nothing (already up to date)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
